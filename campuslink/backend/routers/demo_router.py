@router.post("/simulate-offer")
def simulate_offer_workflow(db: Session = Depends(get_db)):
    """
    Simulates Step 10 & 11:
    Advances candidate Rahul Sharma to Selected, generates an 8 LPA offer, and sets Offer Accepted!
    """
    stu = db.query(models.Student).filter(models.Student.email == "rahul@campuslink.edu").first()
    job = db.query(models.Job).filter(models.Job.title.ilike("%Java%")).first()

    if not stu or not job:
        raise HTTPException(status_code=400, detail="Demo student or Java job not found. Please click 'Reset Seed Data' first.")

    # Find or create application
    app = db.query(models.Application).filter(
        models.Application.student_id == stu.id,
        models.Application.job_id == job.id
    ).first()

    if not app:
        app = models.Application(
            student_id=stu.id,
            job_id=job.id,
            status="SELECTED",
            match_score=88.5
        )
        db.add(app)
        db.commit()
        db.refresh(app)
    else:
        app.status = "OFFER_ACCEPTED"

    # Create or update Offer
    offer = db.query(models.Offer).filter(models.Offer.student_id == stu.id).first()
    if not offer:
        offer = models.Offer(
            application_id=app.id,
            student_id=stu.id,
            recruiter_id=job.recruiter_id,
            job_id=job.id,
            company_name=job.recruiter.company_name,
            role_title=job.title,
            ctc_lpa=8.0,
            offer_date=datetime.utcnow().strftime("%Y-%m-%d"),
            offer_letter_url=f"/uploads/Offer_Rahul_Sharma_TechNova.pdf",
            acceptance_status="ACCEPTED",
            joining_date="2026-12-15",
            joining_status="PENDING",
            documentation_status="VERIFIED",
            remarks="Fast-track selection through AI Matching Arena."
        )
        db.add(offer)
    else:
        offer.acceptance_status = "ACCEPTED"
        offer.ctc_lpa = 8.0
        offer.joining_status = "PENDING"
        offer.documentation_status = "VERIFIED"

    # Dispatch notification
    notif = models.Notification(
        user_id=stu.user_id,
        title="Congratulations! Offer Letter Received",
        message=f"Official Offer Letter generated by {job.recruiter.company_name} for ₹8.0 LPA. Status: Offer Accepted.",
        category="OFFER"
    )
    db.add(notif)
    db.commit()

    return {
        "message": f"Simulated offer generated & accepted for Rahul Sharma at {job.recruiter.company_name} (₹8.0 LPA).",
        "student": stu.name,
        "company": job.recruiter.company_name,
        "ctc_lpa": 8.0,
        "status": "OFFER_ACCEPTED",
        "joining": "PENDING"
    }
